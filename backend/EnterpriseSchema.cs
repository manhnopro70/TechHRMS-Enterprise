using Microsoft.EntityFrameworkCore;

namespace TechHRMS.Api;

/// <summary>
/// V3 additive upgrade only. Existing demo SQLite data is preserved; DDL creates NEW tables.
/// Before business deployment, replace EnsureCreated + additive DDL with versioned EF migrations.
/// </summary>
public static class EnterpriseSchema
{
    public static async Task InitializeAsync(IServiceProvider services, IWebHostEnvironment env, IConfiguration config)
    {
        using var scope = services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<HrDb>();
        if (!db.Database.IsSqlite() && !db.Database.IsNpgsql())
            throw new InvalidOperationException("Only SQLite and PostgreSQL are supported.");
        var pg = db.Database.IsNpgsql();
        string id = pg ? "integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT";
        string date = pg ? "date" : "TEXT";
        string instant = pg ? "timestamp with time zone" : "TEXT";
        await db.Database.ExecuteSqlRawAsync($"""
            CREATE TABLE IF NOT EXISTS "EmploymentContracts" (
              "Id" {id}, "EmployeeId" integer NOT NULL,
              "ContractCode" varchar(48) NOT NULL, "ContractType" varchar(32) NOT NULL,
              "StartDate" {date} NOT NULL, "EndDate" {date} NULL,
              "Status" varchar(24) NOT NULL, "Notes" varchar(500) NOT NULL
            )
            """);
        await db.Database.ExecuteSqlRawAsync($"""
            CREATE TABLE IF NOT EXISTS "OnboardingTasks" (
              "Id" {id}, "EmployeeId" integer NOT NULL,
              "Title" varchar(200) NOT NULL, "Category" varchar(30) NOT NULL,
              "OwnerRole" varchar(24) NOT NULL, "DueDate" {date} NULL,
              "Status" varchar(24) NOT NULL, "CompletedAtUtc" {instant} NULL
            )
            """);
        await db.Database.ExecuteSqlRawAsync($"""
            CREATE TABLE IF NOT EXISTS "TimeEntries" (
              "Id" {id}, "EmployeeId" integer NOT NULL,
              "WorkDate" {date} NOT NULL, "Mode" varchar(24) NOT NULL,
              "CheckInUtc" {instant} NOT NULL, "CheckOutUtc" {instant} NULL,
              "Note" varchar(240) NOT NULL
            )
            """);
        await db.Database.ExecuteSqlRawAsync($"""
            CREATE TABLE IF NOT EXISTS "TrainingCourses" (
              "Id" {id}, "Code" varchar(32) NOT NULL,
              "Title" varchar(160) NOT NULL, "Category" varchar(40) NOT NULL,
              "DurationHours" integer NOT NULL, "Status" varchar(24) NOT NULL
            )
            """);
        await db.Database.ExecuteSqlRawAsync($"""
            CREATE TABLE IF NOT EXISTS "TrainingEnrollments" (
              "Id" {id}, "CourseId" integer NOT NULL, "EmployeeId" integer NOT NULL,
              "Status" varchar(24) NOT NULL, "EnrolledAtUtc" {instant} NOT NULL,
              "CompletedAtUtc" {instant} NULL
            )
            """);
        foreach (var sql in new[]
        {
            "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_EmploymentContracts_ContractCode\" ON \"EmploymentContracts\" (\"ContractCode\")",
            "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_TimeEntries_EmployeeId_WorkDate\" ON \"TimeEntries\" (\"EmployeeId\", \"WorkDate\")",
            "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_TrainingCourses_Code\" ON \"TrainingCourses\" (\"Code\")",
            "CREATE UNIQUE INDEX IF NOT EXISTS \"IX_TrainingEnrollments_CourseId_EmployeeId\" ON \"TrainingEnrollments\" (\"CourseId\", \"EmployeeId\")"
        }) await db.Database.ExecuteSqlRawAsync(sql);

        // Seed fictional examples only in development or on explicitly requested demo environments.
        var demo = env.IsDevelopment() || string.Equals(config["SEED_SAMPLE_DATA"], "true", StringComparison.OrdinalIgnoreCase);
        if (!demo) return;
        var employee = await db.Employees.OrderBy(x => x.Id).FirstOrDefaultAsync();
        if (employee is null) return;
        if (!await db.EmploymentContracts.AnyAsync())
            db.EmploymentContracts.Add(new EmploymentContract { EmployeeId = employee.Id, ContractCode = "DEMO-HD-001", ContractType = "FixedTerm", StartDate = new DateOnly(2026, 1, 1), EndDate = new DateOnly(2027, 1, 1), Status = "Active", Notes = "Hợp đồng giả lập; không có giá trị pháp lý." });
        if (!await db.OnboardingTasks.AnyAsync())
            db.OnboardingTasks.AddRange(
                new OnboardingTask { EmployeeId = employee.Id, Title = "Hoàn thành hồ sơ nhân sự mẫu", Category = "HR", OwnerRole = "Employee", Status = "Pending", DueDate = DateOnly.FromDateTime(DateTime.UtcNow).AddDays(5) },
                new OnboardingTask { EmployeeId = employee.Id, Title = "Bàn giao thiết bị làm việc", Category = "IT", OwnerRole = "HR", Status = "Pending" });
        if (!await db.TrainingCourses.AnyAsync())
            db.TrainingCourses.AddRange(
                new TrainingCourse { Code = "SEC-101", Title = "Bảo mật thông tin cho nhân viên Tech", Category = "Compliance", DurationHours = 3 },
                new TrainingCourse { Code = "CLOUD-201", Title = "Cloud Fundamentals & DevOps", Category = "Technical", DurationHours = 8 },
                new TrainingCourse { Code = "LEAD-101", Title = "Giao tiếp và làm việc nhóm", Category = "SoftSkill", DurationHours = 4 });
        await db.SaveChangesAsync();
    }
}
