using System.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Storage;

namespace TechHRMS.Api;

// Interpolated DDL below uses only internal table/column/type constants chosen by database provider.
// User values use ExecuteSqlInterpolated or DbParameter instead.
#pragma warning disable EF1002

/// <summary>Additive, versioned upgrade for the existing V3 database. Never recreates data.</summary>
public static class AccountSchema
{
    public static async Task InitializeAsync(IServiceProvider services)
    {
        using var scope = services.CreateScope();
        var db = scope.ServiceProvider.GetRequiredService<HrDb>();
        await using var tx = await db.Database.BeginTransactionAsync(IsolationLevel.Serializable);
        var pg = db.Database.IsNpgsql();
        if (pg) await db.Database.ExecuteSqlRawAsync("SELECT pg_advisory_xact_lock(47424000)");
        var idType = pg ? "integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT";
        var timeType = pg ? "timestamp with time zone" : "TEXT";
        await db.Database.ExecuteSqlRawAsync($"CREATE TABLE IF NOT EXISTS \"AccountSchemaVersions\" (\"Version\" varchar(50) PRIMARY KEY, \"AppliedAtUtc\" {timeType} NOT NULL)");
        await db.Database.ExecuteSqlRawAsync($"CREATE TABLE IF NOT EXISTS \"DataProtectionKeys\" (\"Id\" {idType}, \"FriendlyName\" TEXT NULL, \"Xml\" TEXT NULL)");
        await AddColumn(db, "MustChangePassword", pg ? "boolean NOT NULL DEFAULT FALSE" : "INTEGER NOT NULL DEFAULT 0");
        await AddColumn(db, "SecurityStamp", "varchar(64) NOT NULL DEFAULT ''");
        await AddColumn(db, "CreatedAtUtc", $"{timeType} NOT NULL DEFAULT '1970-01-01T00:00:00Z'");
        await AddColumn(db, "LastLoginAtUtc", $"{timeType} NULL");

        if (await db.Accounts.GroupBy(x => x.EmployeeId).AnyAsync(g => g.Count() > 1))
            throw new InvalidOperationException("Existing data contains multiple login accounts for one employee. Resolve duplicate accounts before upgrading; no records were removed.");
        await db.Database.ExecuteSqlRawAsync("CREATE UNIQUE INDEX IF NOT EXISTS \"UX_Accounts_EmployeeId\" ON \"Accounts\" (\"EmployeeId\")");
        var existing = await db.Accounts.Where(x => x.SecurityStamp == "" || x.CreatedAtUtc < new DateTime(2000, 1, 1, 0, 0, 0, DateTimeKind.Utc)).ToListAsync();
        foreach (var account in existing)
        {
            if (string.IsNullOrEmpty(account.SecurityStamp)) account.SecurityStamp = Guid.NewGuid().ToString("N");
            if (account.CreatedAtUtc.Year < 2000) account.CreatedAtUtc = DateTime.UtcNow;
        }
        await db.SaveChangesAsync();
        await db.Database.ExecuteSqlInterpolatedAsync($"INSERT INTO \"AccountSchemaVersions\" (\"Version\", \"AppliedAtUtc\") VALUES ({"4.0-accounts"}, {DateTime.UtcNow}) ON CONFLICT (\"Version\") DO NOTHING");
        await tx.CommitAsync();
    }

    private static async Task AddColumn(HrDb db, string name, string definition)
    {
        // Names and definitions are internal constants, never user input.
        var connection = db.Database.GetDbConnection();
        await using var command = connection.CreateCommand();
        command.Transaction = db.Database.CurrentTransaction!.GetDbTransaction();
        if (db.Database.IsSqlite())
        {
            command.CommandText = "PRAGMA table_info(\"Accounts\")";
            await using var reader = await command.ExecuteReaderAsync();
            while (await reader.ReadAsync()) if (reader.GetString(1) == name) return;
        }
        else
        {
            command.CommandText = "SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='Accounts' AND column_name=@name";
            var parameter = command.CreateParameter(); parameter.ParameterName = "name"; parameter.Value = name; command.Parameters.Add(parameter);
            if (await command.ExecuteScalarAsync() is not null) return;
        }
        await db.Database.ExecuteSqlRawAsync($"ALTER TABLE \"Accounts\" ADD COLUMN \"{name}\" {definition}");
    }
}

#pragma warning restore EF1002
